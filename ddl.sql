-- DDL (Oracle 12c+)

CREATE TABLE users (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR2(255) NOT NULL UNIQUE,
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE media_types (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(255) NOT NULL UNIQUE,
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE medias (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR2(255) NOT NULL,
    media_type_id NUMBER NOT NULL REFERENCES media_types(id) ON DELETE CASCADE,
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT medias_unique_title_type UNIQUE (title, media_type_id)
);

CREATE TABLE users_medias (
    user_id NUMBER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    media_id NUMBER NOT NULL REFERENCES medias(id) ON DELETE CASCADE,
    added_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    PRIMARY KEY (user_id, media_id)
);
